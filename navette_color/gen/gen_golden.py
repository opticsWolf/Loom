"""
Generate exact golden vectors from the REAL loom_colorengine reference
(running in pure-Python via the numba shim) and emit a Rust source file
(tests/golden.rs) of const arrays the parity tests assert against.
"""
import numpy as np
import loom_colorengine as ce

E = ce.ColorSpaceEngine
CA = ce.ChromaticAdaptation
CM = ce.ColorMetrics

def fa(a):
    """Format a flat list of f64 as Rust array body."""
    return ", ".join(f"{x:.17e}" for x in np.asarray(a, dtype=np.float64).ravel())

def rows3(name, arr):
    arr = np.atleast_2d(np.asarray(arr, dtype=np.float64))
    n = arr.shape[0]
    body = ",\n    ".join("[" + fa(arr[i]) + "]" for i in range(n))
    return f"pub const {name}: [[f64; 3]; {n}] = [\n    {body},\n];\n"

def rows2(name, arr):
    arr = np.atleast_2d(np.asarray(arr, dtype=np.float64))
    n = arr.shape[0]
    body = ",\n    ".join("[" + fa(arr[i]) + "]" for i in range(n))
    return f"pub const {name}: [[f64; 2]; {n}] = [\n    {body},\n];\n"

def vec(name, arr):
    arr = np.asarray(arr, dtype=np.float64).ravel()
    return f"pub const {name}: [f64; {arr.shape[0]}] = [{fa(arr)}];\n"

def scalar(name, x):
    return f"pub const {name}: f64 = {float(x):.17e};\n"

out = []
out.append("// AUTO-GENERATED by refgen/gen_golden.py from loom_colorengine.py reference.\n")
out.append("// Do not edit by hand. These are exact outputs of the Python reference engine.\n")
out.append("#![allow(clippy::all)]\n")
out.append("#![allow(dead_code)]\n")

# ---- Canonical XYZ input set (spans gamut incl. black + out-of-gamut-ish) ----
XYZ = np.array([
    [0.95047, 1.00000, 1.08883],   # D65 white
    [0.5,     0.5,     0.5    ],   # neutral-ish
    [0.18,    0.10,    0.04   ],   # dark warm
    [0.41246, 0.21267, 0.01933],   # ~ sRGB red primary
    [0.0,     0.0,     0.0    ],   # black
    [0.7,     0.85,    0.35   ],   # greenish
], dtype=np.float64)
out.append(rows3("XYZ_IN", XYZ))

# sRGB input set
SRGB = np.array([
    [1.0, 1.0, 1.0],
    [0.5, 0.5, 0.5],
    [0.8, 0.2, 0.1],
    [0.0, 0.0, 0.0],
    [0.2, 0.6, 0.9],
    [0.95, 0.75, 0.10],
], dtype=np.float64)
out.append(rows3("SRGB_IN", SRGB))

# Lab input set (reference samples for metrics)
LAB1 = np.array([
    [50.0,   2.6772, -79.7751],
    [60.0,  20.0,     10.0   ],
    [ 0.0,   0.0,      0.0   ],
    [80.0, -40.0,     30.0   ],
    [25.0,  50.0,    -20.0   ],
], dtype=np.float64)
LAB2 = np.array([
    [50.0,   0.0,    -82.7485],
    [61.0,  22.0,      8.0   ],
    [ 5.0,   1.0,     -1.0   ],
    [78.0, -38.0,     33.0   ],
    [26.0,  48.0,    -23.0   ],
], dtype=np.float64)
out.append(rows3("LAB1_IN", LAB1))
out.append(rows3("LAB2_IN", LAB2))

# ---- func_01: XYZ <-> xyY ----
out.append(rows3("F01_XYZ_TO_XYY", E.xyz_to_xyY(XYZ)))
out.append(rows3("F01_XYY_TO_XYZ", E.xyY_to_xyz(E.xyz_to_xyY(XYZ))))

# ---- func_02: Lab <-> LCh ----
out.append(rows3("F02_LAB_TO_LCH", E.lab_to_lch(LAB1)))
out.append(rows3("F02_LCH_TO_LAB", E.lch_to_lab(E.lab_to_lch(LAB1))))

# ---- func_03: XYZ <-> Luv ----
out.append(rows3("F03_XYZ_TO_LUV", E.xyz_to_luv(XYZ)))
out.append(rows3("F03_LUV_TO_XYZ", E.luv_to_xyz(E.xyz_to_luv(XYZ))))

# ---- func_04: XYZ <-> Oklab (standard/XYZ pipeline) ----
out.append(rows3("F04_XYZ_TO_OKLAB", E.xyz_to_oklab(XYZ)))
out.append(rows3("F04_OKLAB_TO_XYZ", E.oklab_to_xyz(E.xyz_to_oklab(XYZ))))

# ---- func_05: sRGB <-> Oklab (legacy sRGB pipeline) ----
out.append(rows3("F05_SRGB_TO_OKLAB", E.srgb_to_oklab(SRGB)))
out.append(rows3("F05_OKLAB_TO_SRGB", E.oklab_to_srgb(E.srgb_to_oklab(SRGB))))

# ---- func_06: XYZ <-> CIE1964 UVW (D65 white) ----
out.append(rows3("F06_XYZ_TO_UVW", E.xyz_to_uvw(XYZ)))
out.append(rows3("F06_UVW_TO_XYZ", E.uvw_to_xyz(E.xyz_to_uvw(XYZ))))
# white point un, vn used (1960)
uvp_n = ce._xyz_to_uv_prime(np.atleast_2d(ce.REF_WHITE_D65))
out.append(scalar("F06_UN_D65", uvp_n[0, 0]))
out.append(scalar("F06_VN_D65", (2.0/3.0) * uvp_n[0, 1]))

# ---- func_07: UCS 1960 + chromaticity conversions ----
out.append(rows3("F07_XYZ_TO_UCS", E.xyz_to_ucs(XYZ)))
out.append(rows3("F07_UCS_TO_XYZ", E.ucs_to_xyz(E.xyz_to_ucs(XYZ))))
out.append(rows2("F07_XYZ_TO_UCS_UV", E.xyz_to_ucs_uv(XYZ)))
# uv1976->xy and uv1960->xy on a fixed uv set
UVP = np.array([[0.1978, 0.4683], [0.20, 0.46], [0.25, 0.50]], dtype=np.float64)
out.append(rows2("F07_UVP_IN", UVP))
out.append(rows2("F07_UV1976_TO_XY", E.uv1976_to_xy(UVP)))
out.append(rows2("F07_UV1960_TO_XY", E.uv1960_to_xy(UVP)))

# ---- func_08: Bradford chromatic adaptation D65 -> D50 ----
out.append(rows3("F08_ADAPT_D65_TO_D50", CA.adapt(XYZ, ce.REF_WHITE_D65, ce.REF_WHITE_D50)))
out.append(rows3("F08_BRADFORD_MATRIX", CA.calc_transform_matrix(ce.REF_WHITE_D65, ce.REF_WHITE_D50)))

# ---- func_09/10/11/12: metrics ----
out.append(vec("F09_DE76", CM.delta_E_76(LAB1, LAB2)))
out.append(vec("F10_DE94_GRAPHIC", CM.delta_E_94(LAB1, LAB2)))
out.append(vec("F10_DE94_TEXTILES", CM.delta_E_94(LAB1, LAB2, textiles=True)))
out.append(vec("F11_DE_CMC_2_1", CM.delta_E_CMC(LAB1, LAB2)))            # default pl=2, pc=1
out.append(vec("F11_DE_CMC_1_1", CM.delta_E_CMC(LAB1, LAB2, pl=1.0, pc=1.0)))
out.append(vec("F12_DE_DIN99", CM.delta_E_DIN99(LAB1, LAB2)))
out.append(vec("F12_DE_DIN99_TEX", CM.delta_E_DIN99(LAB1, LAB2, textiles=True)))
# CIEDE2000 (part of the func_01-05 core; include for completeness/regression)
out.append(vec("DE2000", CM.delta_E_2000(LAB1, LAB2)))

# ---- func_13: spectral pipeline ----
# tiny synthetic 8-sample spectrum at 10nm spacing
waves = 8
rng = np.linspace(0, np.pi, waves)
spd = (0.5 + 0.5*np.sin(rng)).astype(np.float64)           # reflectance-ish
illum = (1.0 + 0.2*np.cos(rng)).astype(np.float64)         # illuminant SPD
# fake CMFs (N_waves, 3), positive
xbar = np.abs(np.sin(rng))
ybar = np.abs(np.sin(rng + 0.3))
zbar = np.abs(np.sin(rng + 0.6))
cmfs = np.stack([xbar, ybar, zbar], axis=1).astype(np.float64)
interval = 10.0
out.append(vec("F13_SPD", spd))
out.append(vec("F13_ILLUM", illum))
out.append(rows3("F13_CMFS", cmfs))
out.append(scalar("F13_INTERVAL", interval))
srgb_adapt = ce.SpectralPipeline.spectral_to_srgb(spd, cmfs, illum, interval, apply_adaptation=True)
srgb_noadapt = ce.SpectralPipeline.spectral_to_srgb(spd, cmfs, illum, interval, apply_adaptation=False)
out.append(vec("F13_SRGB_ADAPT", srgb_adapt))
out.append(vec("F13_SRGB_NOADAPT", srgb_noadapt))

# ---- func_14: photometry ----
vp = ybar.copy()                # photopic luminous efficiency (reuse ybar)
vs = np.abs(np.sin(rng + 1.0))  # scotopic
pe = ce.PhotometryEngine(vp, vs)
out.append(vec("F14_VP", vp))
out.append(vec("F14_VS", vs))
out.append(scalar("F14_FLUX_PHOTOPIC", pe.calculate_flux(spd, "photopic", interval=interval)))
out.append(scalar("F14_FLUX_SCOTOPIC", pe.calculate_flux(spd, "scotopic", interval=interval)))
out.append(scalar("F14_FLUX_MESOPIC_05", pe.calculate_flux(spd, "mesopic", m=0.5, interval=interval)))
out.append(scalar("F14_SP_RATIO", pe.calculate_sp_ratio(spd, interval=interval)))
out.append(scalar("F14_KM_P", pe.km_p))
out.append(scalar("F14_KM_S", pe.km_s))

with open("golden.rs", "w") as f:
    f.write("\n".join(out))
print("wrote golden.rs")
print("XYZ->xyY[black] =", E.xyz_to_xyY(np.array([0.0,0.0,0.0])))
print("DE76 =", CM.delta_E_76(LAB1, LAB2))
print("DE2000[0] =", CM.delta_E_2000(LAB1[:1], LAB2[:1]))
